"""Alembic migration environment.

Loads the application's SQLAlchemy metadata from :mod:`app.models` so
that autogenerated revisions always match the ORM exactly. The database
URL is taken from :mod:`app.config.settings` (env-aware).

No imports from :mod:`app.main` or any FastAPI/Redis code happen here,
so migrations are safe to run in a bare worker container.
"""

from __future__ import annotations

import logging
import sys
from logging.config import fileConfig
from pathlib import Path

from alembic import context
from sqlalchemy import engine_from_config, pool

# Ensure the repository root is importable (migrations/ is one level down).
ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.config import settings  # noqa: E402
from app.database.base import Base  # noqa: E402
from app import models  # noqa: E402,F401  (register every ORM table)

logger = logging.getLogger("alembic.env")
config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# The metadata that comparison operations use.
target_metadata = Base.metadata


def _database_url() -> str:
    """Resolve the database URL from the application settings."""
    return settings.DATABASE_URL


def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode (SQL script, no DB connection)."""
    context.configure(
        url=_database_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
        render_as_batch=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run migrations in 'online' mode (connected to the database)."""
    configuration = config.get_section(config.config_ini_section, {})
    configuration["sqlalchemy.url"] = _database_url()

    connectable = engine_from_config(
        configuration,
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            compare_type=True,
            compare_server_default=True,
            render_as_batch=True,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    logger.info("Running alembic in offline mode (URL=%s)", _database_url())
    run_migrations_offline()
else:
    logger.info("Running alembic in online mode (URL=%s)", _database_url())
    run_migrations_online()

