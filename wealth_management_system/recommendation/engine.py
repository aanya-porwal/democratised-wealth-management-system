"""Explainable recommendation engine.

Builds on the legacy ``recommendation_engine`` (tax-aware instrument
ranking) and the asset database to produce *recommendations* — not just
ranked tables. Every recommendation carries:

* a type (instrument / allocation / rebalance / goal / protection / tax)
* a confidence level (high / medium / low)
* a list of plain-language reasons explaining *why* this was chosen

The reasons are generated by inspecting the asset profile, the user's
tax bracket, the goal horizon, liquidity needs and risk level — so the
output reads like a human advisor, not a scoring model.
"""

from __future__ import annotations

import logging
from typing import Dict, List, Optional

from wealth_management_system.assets import ASSET_PROFILES
from wealth_management_system.exceptions import ValidationError
from wealth_management_system.models import (
    AssetClass,
    ConfidenceLevel,
    DeductionBenefit,
    Recommendation,
    RecommendationReason,
    RecommendationType,
    UserProfile,
)
from wealth_management_system.recommendation_engine import (
    best_instruments_for_need,
)
from wealth_management_system.utilities import get_logger

logger: logging.Logger = get_logger(__name__)

# mapping from a recommendation "need" to the bucket it serves
_NEED_TO_TYPE: Dict[str, RecommendationType] = {
    "growth": RecommendationType.ASSET_ALLOCATION,
    "debt": RecommendationType.ASSET_ALLOCATION,
    "gold": RecommendationType.ASSET_ALLOCATION,
    "safe": RecommendationType.ASSET_ALLOCATION,
    "all": RecommendationType.ASSET_ALLOCATION,
}


class RecommendationEngine:
    """Generates explainable recommendations for a user.

    Parameters
    ----------
    top_n:
        Number of instruments to consider per need.
    """

    def __init__(self, top_n: int = 5) -> None:
        self._top_n = top_n

    # ── public API ──────────────────────────────────────────────────

    def recommend(self, user: UserProfile) -> List[Recommendation]:
        """Generate an explainable recommendation set for a user.

        Parameters
        ----------
        user:
            The user to advise.

        Returns
        -------
        List[Recommendation]
            Ordered recommendations (most important first).
        """
        recommendations: List[Recommendation] = []

        # instrument-level recommendations across the common needs
        recommendations.extend(self._instrument_recommendations(user))
        # protection gap
        recommendations.extend(self._protection_recommendations(user))
        # tax efficiency
        recommendations.extend(self._tax_recommendations(user))

        return recommendations

    def recommend_instruments(
        self, user: UserProfile, need: str, years: float
    ) -> List[Recommendation]:
        """Explainable instrument picks for a single need.

        Parameters
        ----------
        user:
            The user to advise.
        need:
            One of ``"safe"``, ``"debt"``, ``"growth"``, ``"gold"``,
            ``"all"``.
        years:
            Investment horizon in years.

        Returns
        -------
        List[Recommendation]
            One recommendation per picked instrument with reasons.
        """
        tax_bracket = user.financial.tax_bracket_percent / 100
        monthly = max(user.investable_surplus(), 500)

        df = best_instruments_for_need(
            need=need,
            tax_bracket=tax_bracket,
            has_80c_headroom=self._has_80c_headroom(user),
            has_nps_headroom=self._has_nps_headroom(user),
            years=years,
            monthly_investment=monthly,
            top_n=self._top_n,
        )

        recommendations: List[Recommendation] = []
        for row in df.itertuples():
            ac = AssetClass(row.instrument)
            recommendations.append(
                self._build_instrument_recommendation(user, ac, need, years)
            )
        return recommendations

    # ── instrument recommendation ────────────────────────────────────

    def _instrument_recommendations(self, user: UserProfile) -> List[Recommendation]:
        """Recommend instruments for the dominant needs."""
        horizons = self._goal_horizons(user)
        recommendations: List[Recommendation] = []

        # growth need — long term
        growth_years = horizons.get("growth", 7.0)
        recommendations.extend(self.recommend_instruments(user, "growth", growth_years))

        # debt need — shorter / stability
        debt_years = max(horizons.get("debt", 3.0), 3.0)
        recommendations.extend(self.recommend_instruments(user, "debt", debt_years))

        # gold diversifier
        recommendations.extend(self.recommend_instruments(user, "gold", max(growth_years, 5.0)))

        return recommendations

    def _build_instrument_recommendation(
        self,
        user: UserProfile,
        asset_class: AssetClass,
        need: str,
        years: float,
    ) -> Recommendation:
        """Build one explainable recommendation for a single instrument."""
        profile = ASSET_PROFILES[asset_class]
        rec_type = _NEED_TO_TYPE.get(need, RecommendationType.INSTRUMENT)
        title = f"Consider {asset_class.value.replace('_', ' ')}"
        description = profile.description

        recommendation = Recommendation(
            recommendation_type=rec_type,
            title=title,
            description=description,
            confidence=self._confidence(user, asset_class, years, need),
        )

        self._add_common_reasons(recommendation, user, asset_class, years)
        self._add_need_reason(recommendation, need)
        return recommendation

    # ── reason generators ───────────────────────────────────────────

    def _add_common_reasons(
        self,
        rec: Recommendation,
        user: UserProfile,
        asset_class: AssetClass,
        years: float,
    ) -> None:
        """Attach the shared reasons (tax, horizon, risk, diversification)."""
        profile = ASSET_PROFILES[asset_class]

        # tax benefit
        if profile.deduction_benefit == DeductionBenefit.SECTION_80C:
            rec.add_reason("saves tax via Section 80C (up to ₹1.5L/year)", weight=1.0)
        elif profile.deduction_benefit == DeductionBenefit.BOTH_80C_80CCD:
            rec.add_reason("saves tax via 80C + additional 80CCD(1B) ₹50K", weight=1.0)

        # horizon fit
        if profile.min_horizon_years > 0:
            if years >= profile.min_horizon_years:
                rec.add_reason(
                    f"suitable for a {years:.0f}-year horizon"
                    f" (needs {profile.min_horizon_years:.0f}+ yrs)",
                    weight=0.9,
                )
            else:
                rec.add_reason(
                    f"horizon too short — needs {profile.min_horizon_years:.0f}+ years",
                    weight=0.9,
                )

        # risk fit
        user_risk = self._user_risk_level(user)
        if profile.risk_level <= user_risk:
            rec.add_reason(
                f"risk acceptable (risk level {profile.risk_level} vs your {user_risk})",
                weight=0.8,
            )
        else:
            rec.add_reason(
                f"riskier than your profile (level {profile.risk_level} vs your {user_risk})",
                weight=0.8,
            )

        # diversification
        rec.add_reason("adds diversification to the portfolio", weight=0.7)

    def _add_need_reason(self, rec: Recommendation, need: str) -> None:
        """Attach the need-specific reason."""
        need_text = {
            "growth": "supports long-term wealth creation",
            "debt": "provides stability and income",
            "gold": "hedges equity risk and inflation",
            "safe": "preserves capital with liquidity",
            "all": "improves overall portfolio balance",
        }
        if need in need_text:
            rec.add_reason(need_text[need], weight=0.6)

    # ── protection & tax ────────────────────────────────────────────

    def _protection_recommendations(self, user: UserProfile) -> List[Recommendation]:
        """Flag missing protection (insurance)."""
        recommendations: List[Recommendation] = []
        financial = user.financial

        if not financial.has_health_insurance:
            recommendations.append(
                Recommendation(
                    recommendation_type=RecommendationType.PROTECTION,
                    title="Buy health insurance",
                    description="A single medical event can erase years of savings.",
                    confidence=ConfidenceLevel.HIGH,
                    reasons=[
                        RecommendationReason(
                            "no health cover found", weight=1.0
                        ),
                        RecommendationReason(
                            "a hospital bill would force premature withdrawals",
                            weight=0.9,
                        ),
                    ],
                )
            )
        if user.dependents > 0 and not financial.has_term_life_insurance:
            recommendations.append(
                Recommendation(
                    recommendation_type=RecommendationType.PROTECTION,
                    title="Buy term life cover",
                    description=f"{user.dependents} dependent(s) rely on your income.",
                    confidence=ConfidenceLevel.HIGH,
                    reasons=[
                        RecommendationReason("dependents depend on your income", weight=1.0),
                        RecommendationReason("term cover is cheap at your age", weight=0.8),
                    ],
                )
            )
        return recommendations

    def _tax_recommendations(self, user: UserProfile) -> List[Recommendation]:
        """Recommend tax-efficient instruments when the bracket warrants it."""
        recommendations: List[Recommendation] = []
        bracket = user.financial.tax_bracket_percent / 100
        if bracket < 0.20:
            return recommendations  # not much to save

        if self._has_80c_headroom(user):
            recommendations.append(
                Recommendation(
                    recommendation_type=RecommendationType.TAX,
                    title="Use your Section 80C limit",
                    description=(
                        f"At a {bracket:.0%} tax rate, a full ₹1.5L 80C investment "
                        "saves up to "
                        f"{150000 * bracket:,.0f}/year in tax."
                    ),
                    confidence=ConfidenceLevel.HIGH,
                    reasons=[
                        RecommendationReason("80C headroom is available", weight=1.0),
                        RecommendationReason(
                            f"potential tax saving ₹{150000 * bracket:,.0f}/year",
                            weight=0.9,
                        ),
                    ],
                    impact=f"≈ ₹{150000 * bracket:,.0f} saved per year",
                )
            )
        if self._has_nps_headroom(user):
            recommendations.append(
                Recommendation(
                    recommendation_type=RecommendationType.TAX,
                    title="Top up NPS for extra 80CCD(1B)",
                    description="An extra ₹50K into NPS Tier 1 saves tax on top of 80C.",
                    confidence=ConfidenceLevel.MEDIUM,
                    reasons=[
                        RecommendationReason("80CCD(1B) headroom is available", weight=1.0),
                        RecommendationReason(
                            f"extra saving ~₹{50000 * bracket:,.0f}/year", weight=0.8
                        ),
                    ],
                )
            )
        return recommendations

    # ── helpers ─────────────────────────────────────────────────────

    @staticmethod
    def _has_80c_headroom(user: UserProfile) -> bool:
        """Whether the user likely has Section 80C capacity left."""
        return user.financial.existing_monthly_sip * 12 < 150000

    @staticmethod
    def _has_nps_headroom(user: UserProfile) -> bool:
        """Whether the user likely has NPS 80CCD(1B) capacity left."""
        return user.financial.tax_bracket_percent >= 20

    def _user_risk_level(self, user: UserProfile) -> int:
        """Map the user's risk score (0-100) to an asset risk level (1-10)."""
        from wealth_management_system.risk_engine import assess_risk

        score = assess_risk(user).final_score_100
        return min(10, max(1, round(score / 10)))

    def _goal_horizons(self, user: UserProfile) -> Dict[str, float]:
        """Distil the user's goals into growth/debt horizon anchors."""
        horizons: Dict[str, float] = {}
        if not user.goals:
            return {"growth": 7.0, "debt": 3.0}
        years_list = [max(g.years_to_goal(), 0.5) for g in user.goals]
        avg = sum(years_list) / len(years_list)
        horizons["growth"] = max(avg, 5.0)
        horizons["debt"] = max(min(avg, 5.0), 0.5)
        return horizons

    def _confidence(
        self,
        user: UserProfile,
        asset_class: AssetClass,
        years: float,
        need: str,
    ) -> ConfidenceLevel:
        """Heuristic confidence based on fit between the user and product."""
        profile = ASSET_PROFILES[asset_class]
        score = 0.0

        if years >= profile.min_horizon_years:
            score += 0.4
        if profile.risk_level <= self._user_risk_level(user):
            score += 0.3
        if profile.min_investment <= max(user.investable_surplus(), 500):
            score += 0.3

        if score >= 0.8:
            return ConfidenceLevel.HIGH
        if score >= 0.5:
            return ConfidenceLevel.MEDIUM
        return ConfidenceLevel.LOW

